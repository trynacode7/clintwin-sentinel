/**
 * ScenarioComparisonChart
 * =======================
 * Renders aligned physiological trajectory time-series across multiple BioGears scenarios.
 * Displays separate, synchronized lines with no synthetic interpolation.
 * Highlights the strictly verified common observation window.
 */
export default function ScenarioComparisonChart({
  alignedData = [],
  scenarios = [],
  commonInterval = [0, 0],
  maxDuration = 0,
}) {
  const [activeMetricId, setActiveMetricId] = useState('hr');
  const activeMetric = useMemo(() => {
    return METRICS.find((m) => m.id === activeMetricId) || METRICS[0];
  }, [activeMetricId]);

  const [commonMin, commonMax] = commonInterval || [0, 0];
  const hasExtendedPeriod = maxDuration > commonMax && commonMax > 0;

  if (!alignedData || alignedData.length === 0 || scenarios.length === 0) {
    return (
      <div className="p-8 text-center bg-slate-900/40 rounded-xl border border-slate-800/60 text-slate-400 text-xs">
        <svg className="w-8 h-8 mx-auto mb-2 text-slate-600" fill="none" viewBox="0 0 24 24" stroke="currentColor">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M9 19v-6a2 2 0 00-2-2H5a2 2 0 00-2 2v6a2 2 0 002 2h2a2 2 0 002-2zm0 0V9a2 2 0 012-2h2a2 2 0 012 2v10m-6 0a2 2 0 002 2h2a2 2 0 002-2m0 0V5a2 2 0 012-2h2a2 2 0 012 2v14a2 2 0 01-2 2h-2a2 2 0 01-2-2z" />
        </svg>
        <p className="font-medium text-slate-300">No comparison trajectory available</p>
        <p className="text-[11px] text-slate-500 mt-1">
          Simulate at least two valid scenarios to generate comparative trajectory overlays.
        </p>
      </div>
    );
  }

  return (
    <div className="bg-slate-900/60 rounded-xl border border-slate-800/80 p-4 space-y-4">
      {/* Metric Switcher Header */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <h4 className="text-xs font-semibold text-slate-200 uppercase tracking-wider">
              {activeMetric.label} Comparison Trajectory
            </h4>
            <span className="text-[10px] font-mono text-cyan-400/90 bg-cyan-950/40 border border-cyan-800/40 px-2 py-0.5 rounded">
              {scenarios.length} Strategies Overlay
            </span>
            <span className="text-[10px] font-mono text-slate-400 bg-slate-950/60 border border-slate-800 px-2 py-0.5 rounded">
              Unit: {activeMetric.unit}
            </span>
          </div>
          <p className="text-[11px] text-slate-400 mt-0.5">
            {activeMetric.description} • Real simulated observations only (no extrapolation)
          </p>
        </div>

        {/* Tab Buttons for Vitals */}
        <div className="flex flex-wrap items-center gap-1 bg-slate-950/80 p-1 rounded-lg border border-slate-800 text-xs">
          {METRICS.map((metric) => (
            <button
              key={metric.id}
              onClick={() => setActiveMetricId(metric.id)}
              className={`px-3 py-1 rounded-md transition-all font-medium cursor-pointer ${
                activeMetricId === metric.id
                  ? 'bg-cyan-500/20 text-cyan-300 border border-cyan-500/30 shadow-sm'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              {metric.abbr} ({metric.unit})
            </button>
          ))}
        </div>
      </div>

      {/* Common Time Interval Legend & Notification */}
      <div className="flex flex-wrap items-center justify-between gap-2 px-3 py-2 rounded-lg bg-slate-950/50 border border-slate-800 text-[11px]">
        <div className="flex items-center gap-2 text-slate-300">
          <span className="w-2.5 h-2.5 rounded bg-emerald-500/40 border border-emerald-400 inline-block" />
          <span>
            Strict Common Interval: <span className="font-mono text-emerald-300 font-semibold">{commonMin}s – {commonMax}s</span>
            {' '}(all {scenarios.length} strategies observed simultaneously)
          </span>
        </div>
        {hasExtendedPeriod && (
          <div className="text-slate-400 flex items-center gap-1 font-mono text-[10px]">
            <span className="text-amber-400 font-bold">ℹ</span>
            <span>
              Unmatched period: {commonMax}s – {maxDuration}s (shorter strategies display null to avoid false extrapolation)
            </span>
          </div>
        )}
      </div>

      {/* Trajectory Overlay Chart */}
      <div className="h-72 w-full">
        <ResponsiveContainer width="100%" height="100%">
          <ComposedChart
            data={alignedData}
            margin={{ top: 12, right: 25, left: 10, bottom: 20 }}
          >
            <CartesianGrid strokeDasharray="3 3" stroke="rgba(148, 163, 184, 0.08)" />

            <XAxis
              dataKey="time_s"
              type="number"
              domain={['dataMin', 'dataMax']}
              tick={{ fontSize: 10, fill: '#64748b' }}
              tickLine={false}
              axisLine={{ stroke: 'rgba(148, 163, 184, 0.2)' }}
              unit="s"
              label={{
                value: 'Elapsed Simulation Time (seconds)',
                position: 'insideBottom',
                offset: -12,
                fill: '#64748b',
                fontSize: 10,
              }}
            />

            <YAxis
              orientation="left"
              domain={activeMetric.domain}
              tick={{ fontSize: 10, fill: '#94a3b8' }}
              tickLine={false}
              axisLine={{ stroke: 'rgba(148, 163, 184, 0.2)' }}
              width={50}
              unit={` ${activeMetric.unit}`}
            />

            <Tooltip
              content={
                <ComparisonTooltip
                  activeMetric={activeMetric}
                  scenarios={scenarios}
                  commonInterval={commonInterval}
                />
              }
            />

            {/* Shaded Area for Common Observation Interval */}
            {commonMax > 0 && (
              <ReferenceArea
                x1={commonMin}
                x2={commonMax}
                fill="rgba(16, 185, 129, 0.04)"
                stroke="rgba(16, 185, 129, 0.15)"
                strokeDasharray="2 2"
              />
            )}

            {/* Common Horizon Reference Line if extended */}
            {hasExtendedPeriod && (
              <ReferenceLine
                x={commonMax}
                stroke="#f59e0b"
                strokeDasharray="3 3"
                strokeWidth={1}
                label={{
                  value: 'Common Horizon End',
                  position: 'insideTopRight',
                  fill: '#f59e0b',
                  fontSize: 9,
                }}
              />
            )}

            {/* Scenario Trajectory Lines */}
            {scenarios.map((scenario) => (
              <Line
                key={scenario.id}
                type="monotone"
                dataKey={`${activeMetric.dataKeyPrefix}_${scenario.id}`}
                name={scenario.name}
                stroke={scenario.color}
                strokeWidth={2.4}
                dot={false}
                connectNulls={false}
                isAnimationActive={false}
              />
            ))}
          </ComposedChart>
        </ResponsiveContainer>
      </div>

      {/* Legend & Strategy Cards Indicator */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-2.5 pt-2 border-t border-slate-800/80">
        {scenarios.map((s) => (
          <div
            key={s.id}
            className="flex items-center gap-2.5 px-3 py-2 rounded-lg bg-slate-950/70 border text-xs"
            style={{ borderColor: s.color ? `${s.color}40` : 'rgba(148, 163, 184, 0.2)' }}
          >
            <span
              className="w-3 h-3 rounded-full flex-shrink-0"
              style={{ backgroundColor: s.color }}
            />
            <div className="min-w-0 flex-1">
              <p className="font-semibold text-slate-200 truncate">{s.name}</p>
              <p className="text-[10px] text-slate-400 font-mono">
                Duration: {s.maxTime}s • {s.actions?.length ?? 1} Bolus{s.actions?.length > 1 ? 'es' : ''}
              </p>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}
